"""Generate docs/reference/rules.md from the rule pack and the validator checks.

Run after changing the rule pack or the checks:  .venv/bin/python scripts/gen_docs.py
The docs test fails if the generated page is out of date.
"""
from __future__ import annotations

from pathlib import Path

from sfal.rules import load_rules
from sfal.validate import CHECKS

OUT = Path(__file__).resolve().parents[1] / "docs" / "reference" / "rules.md"
LEVEL = {"block": "Blocks commit", "warn": "Warning", "hold": "Holds row"}


def render() -> str:
    r = load_rules()
    L = ["<!-- GENERATED by scripts/gen_docs.py from the rule pack and validator - do not edit by hand -->",
         "# Rules reference", "",
         f"Rule pack **`{r.version}`** - source: {r.source}.",
         "These rules are enforced by the engine on every proposed row, whatever AI tool you use.", "",
         "## Account routing", "", "| Situation | Account |", "|---|---|"]
    for x in r.routing:
        acct = r.internal_account if x["account"] == "internal_account" else x["account"]
        L.append(f"| {x['situation']} | {acct} |")
    L += ["", "## Activity types (drop-down order)", "", "| Type | When to use |", "|---|---|"]
    for t in r.activity_types:
        L.append(f"| {t['num']} · {t['name']} | {t['definition']} |")
    L += ["", "## Field values", "",
          f"- **Status:** {', '.join(r.statuses)} (default {r.default_status})",
          f"- **Solution Area:** {', '.join(r.solution_areas)} - optional; 'Other' needs 'Other: ...' in Notes",
          f"- **One record per engagement** (hours accrue, Activity Date = latest): "
          f"{', '.join(r.type_codes[n] for n in r.consolidated_types)}",
          f"- **Opportunity expected:** {', '.join(r.type_codes[n] for n in r.opportunity_expected_types)}",
          f"- **Partner account is right for:** {', '.join(r.type_codes[n] for n in r.partner_enablement_types)} "
          "(partner enablement); deals are logged under the customer", "",
          "## Checks", "",
          "| Check | Effect | Rule |", "|---|---|---|"]
    for code, (level, text) in CHECKS.items():
        L.append(f"| {code} | {LEVEL[level]} | {text} |")
    L += ["", "A row whose hours, account or no-opportunity reason is `[to confirm]` is valid but **held**:",
          "it is kept in the ledger and left out of Paste-Ready until you resolve it.", ""]
    return "\n".join(L)


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(), encoding="utf-8")
    print(OUT)
